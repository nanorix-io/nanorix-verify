// isNonCanonicalEncoding reports whether the 255-bit y coordinate is >= p
// (2^255-19), i.e. the point has a second, non-canonical encoding.
func isNonCanonicalEncoding(b []byte) bool {
	if len(b) != 32 || b[31]&0x7f != 0x7f || b[0] < 0xed {
		return false
	}
	for _, v := range b[1:31] {
		if v != 0xff {
			return false
		}
	}
	return true
}

func hasSmallOrderEncoding(b []byte) bool {
	if isNonCanonicalEncoding(b) {
		return true
	}
	for i := range smallOrderEncodings {
		if bytes.Equal(b, smallOrderEncodings[i][:]) {
			return true
		}
	}
	return false
}

// verifyEd25519Strict is Ed25519 verification that also rejects a small-order
// public key or a small-order R (ed25519-dalek verify_strict semantics). Under
// a small-order key one signature verifies for many messages, and Go's
// crypto/ed25519 has no strict mode of its own. Canonical S is already
// enforced by ed25519.Verify.
func verifyEd25519Strict(pub, msg, sig []byte) bool {
	if len(pub) != ed25519.PublicKeySize || len(sig) != ed25519.SignatureSize {
		return false
	}
	if hasSmallOrderEncoding(pub) || hasSmallOrderEncoding(sig[:32]) {
		return false
	}
	return ed25519.Verify(pub, msg, sig)
}
